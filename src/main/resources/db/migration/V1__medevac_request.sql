CREATE SEQUENCE IF NOT EXISTS revinfo_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE IF NOT EXISTS medevac_request
(
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    location                   VARCHAR(255)                            NOT NULL,
    radio_freq                 VARCHAR(255)                            NOT NULL,
    patient_number             INTEGER                                 NOT NULL,
    patient_precedence         VARCHAR(255)                            NOT NULL,
    special_equipment          VARCHAR(255)                            NOT NULL,
    patient_litter             INTEGER                                 NOT NULL,
    patient_ambulatory         INTEGER                                 NOT NULL,
    site_security              VARCHAR(255)                            NOT NULL,
    site_marking               VARCHAR(255)                            NOT NULL,
    patient_nationality_status VARCHAR(255)                            NOT NULL,
    terrain_description        VARCHAR(255)                            NOT NULL,
    status                     VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_medevac_request PRIMARY KEY (id)
);

CREATE TABLE revchanges
(
    rev        BIGINT NOT NULL,
    entityname VARCHAR(255)
);

CREATE TABLE revinfo
(
    rev      BIGINT NOT NULL,
    revtstmp BIGINT,
    CONSTRAINT pk_revinfo PRIMARY KEY (rev)
);

